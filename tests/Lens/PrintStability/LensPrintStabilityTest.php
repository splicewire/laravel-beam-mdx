<?php

namespace Splicewire\Beam\Mdx\Tests\Lens\PrintStability;

use PHPUnit\Framework\Attributes\DataProvider;
use Splicewire\Beam\Mdx\Lens\NodeMdxLens;
use Splicewire\Beam\Mdx\Tests\TestCase;

/**
 * Pins the MDX lens print over a corpus of real docs bodies. A blocks row's `asserted_hash` is the hash of this
 * print, so a print that moves re-hashes every blocks row (see {@see LensPrintCorpus::RESTAMP_NOTE}).
 *
 * The lens runs in Node from a host's node_modules: set `BEAM_MDX_LENS_HOST` to a root holding
 * `@splicewire/beam-mdx` built (a beam JS checkout serves), or these tests skip. This test never writes; the
 * expectations are regenerated by `composer lens-print:regenerate`.
 */
final class LensPrintStabilityTest extends TestCase
{
    public function test_the_corpus_is_whole(): void
    {
        $slugs = LensPrintCorpus::slugs();

        // An emptied or truncated corpus must not pass as a stable print.
        $this->assertGreaterThanOrEqual(25, count($slugs), 'the lens-print corpus lost items');
        foreach ($slugs as $slug) {
            $this->assertFileExists(LensPrintCorpus::sourcePath($slug));
            $this->assertFileExists(LensPrintCorpus::printPath($slug), "no committed print for [{$slug}]: run composer lens-print:regenerate -- --write");
            $this->assertNotSame('', trim(LensPrintCorpus::body($slug)), "[{$slug}] has no body");
        }
    }

    /** @return iterable<string, array{string}> */
    public static function corpus(): iterable
    {
        foreach (LensPrintCorpus::slugs() as $slug) {
            yield $slug => [$slug];
        }
    }

    #[DataProvider('corpus')]
    public function test_the_print_of_a_lowered_docs_body_is_byte_stable(string $slug): void
    {
        [$lens, $identity] = $this->lens();

        $this->assertSame(
            file_get_contents(LensPrintCorpus::printPath($slug)),
            LensPrintCorpus::printOnce($lens, LensPrintCorpus::body($slug)),
            "[{$slug}] printed differently with {$identity}.\n".LensPrintCorpus::RESTAMP_NOTE,
        );
    }

    #[DataProvider('corpus')]
    public function test_the_print_is_a_fixed_point(string $slug): void
    {
        [$lens, $identity] = $this->lens();

        $once = LensPrintCorpus::printOnce($lens, LensPrintCorpus::body($slug));

        $this->assertSame(
            $once,
            LensPrintCorpus::printOnce($lens, $once),
            "[{$slug}] print(lower(print(lower(x)))) is not print(lower(x)) with {$identity}: a row stored from its own print "
            .'would re-hash on the next save.',
        );
    }

    /** @return array{NodeMdxLens, string} */
    private function lens(): array
    {
        exec('command -v node', $output, $status);
        if ($status !== 0) {
            $this->markTestSkipped('node is not on PATH.');
        }
        $host = LensPrintCorpus::host();
        if ($host === null) {
            $this->markTestSkipped('Set '.LensPrintCorpus::HOST_ENV.' to a host root whose node_modules hold @splicewire/beam-mdx built.');
        }

        return [new NodeMdxLens(workingDirectory: $host), LensPrintCorpus::lensIdentity($host)];
    }
}
